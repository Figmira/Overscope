document.addEventListener('error', e => {
  const im = e.target;
  if (!(im instanceof HTMLImageElement) || !im.classList.contains('os-img')) return;
  imageFailures.add(im.getAttribute('src'));
  const span = document.createElement('span');
  span.className = `img-fallback ${im.className.replace('os-img', '')} role-${im.dataset.role || 'none'}`;
  span.setAttribute('role', 'img');
  span.setAttribute('aria-label', (im.dataset.fallback || 'Image') + ' (failed to load)');
  span.innerHTML = im.dataset.role === 'news' ? `<b>${esc(im.dataset.fallback || 'NEWS')}</b>` : `<b>${esc((im.dataset.fallback || '?').slice(0, 1))}</b>`;
  im.replaceWith(span);
}, true);

