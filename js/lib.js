// ---------- favorites (stored in this browser) ----------
const FAV_KEY = 'overscope.favs.v1';
function readFavs() {
  try { const f = JSON.parse(localStorage.getItem(FAV_KEY) || '{}'); return { players: Array.isArray(f.players) ? f.players : [], heroes: Array.isArray(f.heroes) ? f.heroes : [] }; }
  catch { return { players: [], heroes: [] }; }
}
function writeFavs(f) { try { localStorage.setItem(FAV_KEY, JSON.stringify(f)); } catch { toast('Browser storage is unavailable, so favorites cannot be saved'); } }
export const favorites = () => readFavs();
export const isFavPlayer = id => readFavs().players.some(p => p.id === id);
export const isFavHero = key => readFavs().heroes.includes(key);
/** Favorites live only in this browser. */
export async function toggleFavPlayer(p) {
  const f = readFavs();
  const on = !f.players.some(x => x.id === p.id);
  f.players = on ? [...f.players, { id: p.id, name: p.name || p.id, avatar: p.avatar || '' }] : f.players.filter(x => x.id !== p.id);
  writeFavs(f);
  return on;
}
export function toggleFavHero(key) {
  const f = readFavs();
  const on = !f.heroes.includes(key);
  f.heroes = on ? [...f.heroes, key] : f.heroes.filter(k => k !== key);
  writeFavs(f);
  return on;
}
