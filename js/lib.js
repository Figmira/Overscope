// Player rank divisions, and the subset the official hero-rates tables can be filtered by.
export const PLAYER_DIVISIONS = ['bronze', 'silver', 'gold', 'platinum', 'emerald', 'diamond', 'master', 'grandmaster', 'champion'];
export const DIVISIONS = PLAYER_DIVISIONS.slice(0, 8);
export const cap = s => (s ? s[0].toUpperCase() + s.slice(1) : '');
/** Inverse of the server's rankValue(): 1..40 → "Gold 3" */
export function rankLabel(v) {
  if (v == null) return '—';
  const d = Math.floor((v - 1) / 5), tier = 6 - (v - d * 5);
  return `${cap(PLAYER_DIVISIONS[d])} ${tier}`;
}
